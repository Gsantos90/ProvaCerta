import { readFile, writeFile } from 'node:fs/promises'

const sqlString = (value) => `'${String(value ?? '').replaceAll("'", "''")}'`
const normalizeExtractedText = (value) => String(value ?? '')
  .replace(/P´ agina \d+ de \d+.*?(?=Leia|TEXTO|Quest)/g, '')
  .replace(/m´\s*usica/g, 'música')
  .replace(/´\s*ı/gi, 'í')
  .replace(/´\s*([aeiou])/gi, (_, letter) => ({ a: 'á', e: 'é', i: 'í', o: 'ó', u: 'ú' }[letter.toLowerCase()] || letter))
  .replace(/([´˜ˆ`])\s*([a-z])/gi, (_, accent, letter) => ({ '´a': 'á', '´e': 'é', '´i': 'í', '´o': 'ó', '´u': 'ú', '˜a': 'ã', '˜e': 'ẽ', '˜i': 'ĩ', '˜o': 'õ', '˜u': 'ũ', '˜n': 'ñ', 'ˆa': 'â', 'ˆe': 'ê', 'ˆi': 'î', 'ˆo': 'ô', 'ˆu': 'û', '`a': 'à', '`e': 'è', '`i': 'ì', '`o': 'ò', '`u': 'ù' }[`${accent}${letter.toLowerCase()}`] || letter))
  .replace(/¸\s*c/gi, 'ç')
  .replace(/P[´']?\s*ágina\s+\d+\s+de\s+\d+/gi, '')
  .replace(/\bnaÁfrica\b/g, 'na África')
  .replace(/\bmãeÁfrica\b/g, 'mãe África')
  .replace(/Pró Reitoria de Graduação Coordenação Geral de Processos Seletivos Pism \d{4} Módulo \d+ \d+º Dia/gi, '')
  .replace(/-\s+/g, '')
  .replace(/\s+/g, ' ')
  .trim()
const mainSource = await readFile('./src/main.jsx', 'utf8')
const extractConstant = (name) => {
  const match = mainSource.match(new RegExp(`const ${name} = (?:'([^']*)'|\`([\\s\\S]*?)\`)`))
  return match ? (match[1] || match[2]) : null
}
const supportBlock = mainSource.match(/const pism2024Day2Texts = \[(.*?)\n\]/s)
const pism2024Day2SupportTexts = supportBlock
  ? [...supportBlock[1].matchAll(/`([\s\S]*?)`/g)].map((match) => match[1])
  : []
const files = [
  ['pism-2024-1', 'PISM 2024-1', '2024-1', './src/2024-1-questions.json'],
  ['pism-2024-2', 'PISM 2024-2', '2024-2', './src/2024-2-questions.json'],
]
const statements = ['-- Generated by scripts/generate-pism-seed.mjs', '']

for (const [slug, title, year, file] of files) {
  const questions = JSON.parse(await readFile(file, 'utf8'))
  statements.push(`insert into public.exams (slug, title, source, year) values (${sqlString(slug)}, ${sqlString(title)}, 'pism', ${sqlString(year)}) on conflict (slug) do update set title = excluded.title;`)
  questions.forEach((question, index) => {
    const support = slug === 'pism-2024-1'
      ? ({ 1: extractConstant('text2024Day1One'), 2: extractConstant('text2024Day1One'), 3: extractConstant('text2024Day1Three'), 4: extractConstant('text2024Day1Four'), 5: extractConstant('text2024Day1Five'), 6: extractConstant('text2024Day1Six'), 7: extractConstant('text2024Day1Seven'), 8: extractConstant('text2024Day1Eight') }[index + 1] || null)
      : slug === 'pism-2024-2' && question.subject === 'Literaturas'
      ? ({ 1: pism2024Day2SupportTexts[0], 2: `${pism2024Day2SupportTexts[0]}\n\n${pism2024Day2SupportTexts[1]}\n\n${pism2024Day2SupportTexts[2]}`, 3: `${pism2024Day2SupportTexts[1]}\n\n${pism2024Day2SupportTexts[2]}`, 4: `${pism2024Day2SupportTexts[3]}\n\n${pism2024Day2SupportTexts[4]}`, 5: pism2024Day2SupportTexts[4] }[index + 1] || null)
      : null
    const supportImage = slug === 'pism-2024-1'
      ? ({ 2: extractConstant('text2024Day1TwoImage'), 9: extractConstant('text2024Day1QuestionNineImage'), 10: extractConstant('text2024Day1QuestionTenImage') }[index + 1] || null)
      : null
    const text = normalizeExtractedText(question.text)
    const options = question.options.map(normalizeExtractedText)
    statements.push(`insert into public.questions (exam_id, number, subject, text, support, support_image, options, answer) select id, ${index + 1}, ${sqlString(question.subject)}, ${sqlString(text)}, ${sqlString(support)}, ${sqlString(supportImage)}, ${sqlString(JSON.stringify(options))}::jsonb, ${sqlString(question.answer)} from public.exams where slug = ${sqlString(slug)} on conflict (exam_id, number) do update set subject = excluded.subject, text = excluded.text, support = excluded.support, support_image = excluded.support_image, options = excluded.options, answer = excluded.answer;`)
  })
}

await writeFile('./supabase/seed-pism-2024.sql', `${statements.join('\n')}\n`, 'utf8')
